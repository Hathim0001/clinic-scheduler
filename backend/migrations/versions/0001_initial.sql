-- Initial schema for the clinic scheduler (plan section 23.2).
-- Every constraint here backs a business rule; see section 23.3 of the plan for which one.
-- Run by migrations/versions/0001_initial.py.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE doctors (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text     NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  speciality       text     NOT NULL CHECK (length(speciality) BETWEEN 1 AND 100),
  slot_length_min  smallint NOT NULL CHECK (slot_length_min IN (15, 30)),
  daily_cap        smallint NOT NULL CHECK (daily_cap BETWEEN 1 AND 96),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE weekly_windows (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id  integer  NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
  weekday    smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),          -- Monday = 0
  start_min  smallint NOT NULL CHECK (start_min BETWEEN 0 AND 1439),
  end_min    smallint NOT NULL CHECK (end_min BETWEEN 1 AND 1440),
  CHECK (end_min > start_min),
  CONSTRAINT weekly_windows_no_overlap EXCLUDE USING gist (
    doctor_id WITH =, weekday WITH =, int4range(start_min, end_min, '[)') WITH &&)
);

CREATE TABLE availability_overrides (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id  integer NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
  on_date    date    NOT NULL CHECK (on_date BETWEEN DATE '2000-01-01' AND DATE '2100-12-31'),
  note       text    CHECK (length(note) <= 200),
  CONSTRAINT overrides_doctor_date_key UNIQUE (doctor_id, on_date)
);

CREATE TABLE override_windows (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  override_id  integer  NOT NULL REFERENCES availability_overrides(id) ON DELETE CASCADE,
  start_min    smallint NOT NULL CHECK (start_min BETWEEN 0 AND 1439),
  end_min      smallint NOT NULL CHECK (end_min BETWEEN 1 AND 1440),
  CHECK (end_min > start_min),
  CONSTRAINT override_windows_no_overlap EXCLUDE USING gist (
    override_id WITH =, int4range(start_min, end_min, '[)') WITH &&)
);

CREATE TABLE patients (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  phone          text NOT NULL CHECK (phone ~ '^\+91[6-9][0-9]{9}$'),
  date_of_birth  date NOT NULL CHECK (date_of_birth BETWEEN DATE '1900-01-01' AND DATE '2100-12-31'),
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT patients_phone_key UNIQUE (phone)
);

CREATE TABLE appointments (
  id                           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id                    integer NOT NULL REFERENCES doctors(id),
  patient_id                   integer NOT NULL REFERENCES patients(id),
  start_at                     timestamptz NOT NULL,
  end_at                       timestamptz NOT NULL,
  status                       text NOT NULL,
  reason                       text NOT NULL CHECK (length(reason) BETWEEN 1 AND 500),
  deposit_required_at_booking  boolean NOT NULL DEFAULT false,
  deposit_confirmed            boolean NOT NULL DEFAULT false,
  cancelled_at                 timestamptz,
  cancelled_by                 text,
  status_changed_at            timestamptz,
  rescheduled_to_id            integer REFERENCES appointments(id),
  created_at                   timestamptz NOT NULL DEFAULT now(),
  updated_at                   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT appt_status_valid     CHECK (status IN ('BOOKED','COMPLETED','CANCELLED','LATE_CANCELLED','NO_SHOW')),
  CONSTRAINT appt_one_slot_long    CHECK (end_at - start_at IN (interval '15 minutes', interval '30 minutes')),
  CONSTRAINT appt_time_bounds      CHECK (start_at >= TIMESTAMPTZ '2000-01-01 00:00:00+00'
                                      AND start_at <  TIMESTAMPTZ '2100-01-01 00:00:00+00'),
  CONSTRAINT appt_cancel_stamp     CHECK ((status IN ('CANCELLED','LATE_CANCELLED')) = (cancelled_at IS NOT NULL)),
  CONSTRAINT appt_cancel_actor     CHECK ((cancelled_at IS NULL) = (cancelled_by IS NULL)),
  CONSTRAINT appt_cancel_actor_val CHECK (cancelled_by IS NULL OR cancelled_by IN ('PATIENT','CLINIC')),
  CONSTRAINT appt_late_is_patient  CHECK (status <> 'LATE_CANCELLED' OR cancelled_by = 'PATIENT'),
  CONSTRAINT appt_changed_stamp    CHECK (status = 'BOOKED' OR status_changed_at IS NOT NULL),
  CONSTRAINT appt_moved_only_if_cancelled CHECK (rescheduled_to_id IS NULL OR status IN ('CANCELLED','LATE_CANCELLED')),
  CONSTRAINT appt_moved_target_unique UNIQUE (rescheduled_to_id),
  CONSTRAINT appt_deposit_ack      CHECK (NOT deposit_required_at_booking OR deposit_confirmed),
  CONSTRAINT no_doctor_overlap EXCLUDE USING gist (
    doctor_id WITH =, tstzrange(start_at, end_at, '[)') WITH &&)
    WHERE (status IN ('BOOKED','COMPLETED','NO_SHOW')),
  CONSTRAINT no_patient_overlap EXCLUDE USING gist (
    patient_id WITH =, tstzrange(start_at, end_at, '[)') WITH &&)
    WHERE (status IN ('BOOKED','COMPLETED','NO_SHOW'))
);

-- Key/value facts written by the seed script (anchor date, queue day) so the UI can offer clock presets.
CREATE TABLE app_meta (
  key    text PRIMARY KEY CHECK (length(key) BETWEEN 1 AND 50),
  value  text NOT NULL CHECK (length(value) <= 200)
);

CREATE INDEX ix_appointments_doctor_start  ON appointments (doctor_id, start_at);
CREATE INDEX ix_appointments_patient_start ON appointments (patient_id, start_at DESC);
CREATE INDEX ix_appointments_penalties     ON appointments (patient_id)
  WHERE status IN ('LATE_CANCELLED', 'NO_SHOW');
